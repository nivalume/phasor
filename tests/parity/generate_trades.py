#!/usr/bin/env python3
"""Generate differential fixtures for the three trade views.

Turning fills into trades needs a rule for attributing exits back to entries,
and the reference ships three of them. They agree on total PnL and disagree on
almost everything else, so a fixture set that only covers simple round trips
proves nothing: it is exactly the cases where the views diverge — partial
exits, reversals, positions still open at the end — that separate a correct
port from a plausible one.

The input here is an **order record stream**, not a simulation. Trade
derivation reads records and nothing else, so feeding it records directly
reaches states a simulation would take many bars to produce, and keeps a
failure localized to the derivation rather than to whatever produced the
fills. Some cases are generated by actually running ``from_orders`` anyway,
to confirm the two agree on realistic input.

Each case is one row per view. Orders are encoded as a single field::

    idx,col,size,price,fees,side | idx,col,size,price,fees,side | ...

with ``side`` being ``Buy`` or ``Sell``. Records must already be grouped by
column and ascending in row within a column, which is the ordering the engine
guarantees and this derivation relies on.

Usage::

    python tests/parity/generate_trades.py

Setup is the same as the other generators; see the README in this directory.
"""

from __future__ import annotations

import argparse
import random
from pathlib import Path

import numpy as np
from vectorbt.portfolio.enums import Direction, SizeType, order_dt, trade_dt
from vectorbt.portfolio.nb import (
    get_entry_trades_nb,
    get_exit_trades_nb,
    get_positions_nb,
    simulate_from_orders_nb,
)
from vectorbt.records.nb import col_map_nb

from generate_execute_order import fmt_float

SIDE_NAMES = {0: "Buy", 1: "Sell"}
SIDE_VALUES = {v: k for k, v in SIDE_NAMES.items()}
DIRECTION_NAMES = {0: "Long", 1: "Short"}
STATUS_NAMES = {0: "Open", 1: "Closed"}

VIEWS = ("EntryTrades", "ExitTrades", "Positions")

OUTPUT_FIELDS = [
    "t_col",
    "t_size",
    "t_entry_idx",
    "t_entry_price",
    "t_entry_fees",
    "t_exit_idx",
    "t_exit_price",
    "t_exit_fees",
    "t_pnl",
    "t_return",
    "t_direction",
    "t_status",
    "t_parent_id",
]

COLUMNS = [
    "case",
    "view",
    "n_rows",
    "n_cols",
    "close",
    "orders",
    "outcome",
    *OUTPUT_FIELDS,
    "note",
]


class Case:
    """An order stream, the close series it is marked against, and a note."""

    def __init__(
        self,
        name: str,
        n_rows: int,
        n_cols: int,
        orders: list[tuple],
        close: list[float],
        note: str = "",
    ) -> None:
        self.name = name
        self.n_rows = n_rows
        self.n_cols = n_cols
        self.orders = orders
        # One close value per column. Only the last row is ever read — an
        # open position is marked to it — so the fixture carries just that.
        assert len(close) == n_cols, "close must carry one value per column"
        self.close = close
        self.note = note

    def orders_text(self) -> str:
        return "|".join(
            f"{i},{c},{fmt_float(sz)},{fmt_float(p)},{fmt_float(f)},{SIDE_NAMES[s]}"
            for i, c, sz, p, f, s in self.orders
        )

    def to_records(self) -> np.ndarray:
        rec = np.empty(len(self.orders), dtype=order_dt)
        for n, (i, c, sz, p, f, s) in enumerate(self.orders):
            rec[n]["id"] = n
            rec[n]["idx"] = i
            rec[n]["col"] = c
            rec[n]["size"] = sz
            rec[n]["price"] = p
            rec[n]["fees"] = f
            rec[n]["side"] = s
        return rec

    def close_2d(self) -> np.ndarray:
        # The derivation only reads the last row, so a constant column is
        # enough and keeps the fixture small.
        return np.full((self.n_rows, self.n_cols), 0.0) + np.asarray(self.close, dtype=float)


def order(i, col, size, price, fees, side) -> tuple:
    return (i, col, float(size), float(price), float(fees), SIDE_VALUES[side])


def run(case: Case, view: str) -> dict[str, str]:
    """Derives one view, returning fixture fields or an error outcome."""
    records = case.to_records()
    close = case.close_2d()
    try:
        col_map = col_map_nb(records["col"], case.n_cols)
        entry = get_entry_trades_nb(records, close, col_map)
        if view == "EntryTrades":
            out = entry
        else:
            exit_ = get_exit_trades_nb(records, close, col_map)
            if view == "ExitTrades":
                out = exit_
            else:
                out = get_positions_nb(exit_, col_map_nb(exit_["col"], case.n_cols))
    except Exception as exc:  # noqa: BLE001 - the error itself is the fixture
        return {"outcome": "error", "note": type(exc).__name__}

    def col(name, fmt=fmt_float):
        return ";".join(fmt(v) for v in out[name])

    return {
        "outcome": "ok",
        "t_col": col("col", str),
        "t_size": col("size"),
        "t_entry_idx": col("entry_idx", str),
        "t_entry_price": col("entry_price"),
        "t_entry_fees": col("entry_fees"),
        "t_exit_idx": col("exit_idx", str),
        "t_exit_price": col("exit_price"),
        "t_exit_fees": col("exit_fees"),
        "t_pnl": col("pnl"),
        "t_return": col("return"),
        "t_direction": col("direction", lambda v: DIRECTION_NAMES[int(v)]),
        "t_status": col("status", lambda v: STATUS_NAMES[int(v)]),
        "t_parent_id": col("parent_id", str),
    }


def handpicked() -> list[Case]:
    """Cases chosen because they separate the three views."""
    cases: list[Case] = []

    cases.append(
        Case(
            "single_round_trip",
            4,
            1,
            [order(0, 0, 1, 10, 0, "Buy"), order(2, 0, 1, 12, 0, "Sell")],
            [12.0],
            "the case all three views agree on",
        )
    )
    cases.append(
        Case(
            "three_entries_one_exit",
            5,
            1,
            [
                order(0, 0, 1, 1, 0, "Buy"),
                order(1, 0, 1, 2, 0, "Buy"),
                order(2, 0, 1, 3, 0, "Buy"),
                order(3, 0, 3, 10, 0, "Sell"),
            ],
            [10.0],
            "three entry trades, one exit trade, one position",
        )
    )
    cases.append(
        Case(
            "one_entry_three_exits",
            5,
            1,
            [
                order(0, 0, 3, 2, 0, "Buy"),
                order(1, 0, 1, 10, 0, "Sell"),
                order(2, 0, 1, 11, 0, "Sell"),
                order(3, 0, 1, 12, 0, "Sell"),
            ],
            [12.0],
            "one entry trade, three exit trades: the mirror case",
        )
    )
    cases.append(
        Case(
            "partial_exit_leaves_position_open",
            4,
            1,
            [order(0, 0, 3, 2, 0, "Buy"), order(1, 0, 1, 10, 0, "Sell")],
            [8.0],
            "the open remainder must be marked to the last close",
        )
    )
    cases.append(
        Case(
            "reversal_in_one_fill",
            3,
            1,
            [order(0, 0, 1, 10, 0, "Buy"), order(1, 0, 3, 12, 0, "Sell")],
            [11.0],
            "one fill closes a long and opens a short; fees split by size",
        )
    )
    cases.append(
        Case(
            "reversal_with_fees",
            3,
            1,
            [order(0, 0, 1, 10, 0.5, "Buy"), order(1, 0, 4, 12, 2.0, "Sell")],
            [11.0],
            "the splitting fill's fees are prorated between two positions",
        )
    )
    cases.append(
        Case(
            "short_round_trip",
            3,
            1,
            [order(0, 0, 2, 10, 0, "Sell"), order(1, 0, 2, 6, 0, "Buy")],
            [6.0],
            "a short profits when the price falls; size stays positive",
        )
    )
    cases.append(
        Case(
            "short_opened_and_left_open",
            4,
            1,
            [order(0, 0, 2, 10, 0.2, "Sell")],
            [7.0],
            "open short marked to close, exit fees zero",
        )
    )
    cases.append(
        Case(
            "two_positions_in_sequence",
            6,
            1,
            [
                order(0, 0, 1, 10, 0, "Buy"),
                order(1, 0, 1, 12, 0, "Sell"),
                order(2, 0, 1, 8, 0, "Buy"),
                order(3, 0, 1, 9, 0, "Sell"),
            ],
            [9.0],
            "parent ids must advance across closed positions",
        )
    )
    cases.append(
        Case(
            "two_columns",
            3,
            2,
            [
                order(0, 0, 1, 10, 0, "Buy"),
                order(1, 0, 1, 12, 0, "Sell"),
                order(0, 1, 1, 10, 0, "Sell"),
                order(1, 1, 1, 12, 0, "Buy"),
            ],
            [12.0, 12.0],
            "parent ids run across columns, not within them",
        )
    )
    cases.append(
        Case(
            "column_with_no_orders",
            3,
            3,
            [order(0, 1, 1, 10, 0, "Buy"), order(1, 1, 1, 12, 0, "Sell")],
            [12.0, 12.0, 12.0],
            "empty columns on both sides of an active one",
        )
    )
    cases.append(
        Case(
            "exit_within_tolerance_of_full",
            3,
            1,
            [
                order(0, 0, 1.0, 10, 0, "Buy"),
                order(1, 0, np.nextafter(1.0, 0.0), 12, 0, "Sell"),
            ],
            [12.0],
            "an exit a few ULP short of the position must close it, not leave dust",
        )
    )
    cases.append(
        Case(
            "exit_just_over_full_reverses",
            3,
            1,
            [
                order(0, 0, 1.0, 10, 0, "Buy"),
                order(1, 0, 1.5, 12, 0, "Sell"),
            ],
            [12.0],
            "the other side of the same boundary: a real reversal",
        )
    )
    cases.append(
        Case(
            "accumulate_then_partially_reduce_then_close",
            6,
            1,
            [
                order(0, 0, 2, 4, 0.1, "Buy"),
                order(1, 0, 2, 6, 0.1, "Buy"),
                order(2, 0, 1, 9, 0.1, "Sell"),
                order(3, 0, 3, 11, 0.1, "Sell"),
            ],
            [11.0],
            "scaling in and out: where the two views' fee attribution diverges",
        )
    )
    cases.append(
        Case(
            "break_even_round_trip_leaves_a_residue",
            4,
            1,
            [
                order(0, 0, 4.745, 41.082, 0, "Buy"),
                order(1, 0, 2.035, 41.082, 0, "Buy"),
                order(2, 0, 0.337, 41.082, 0, "Buy"),
                order(3, 0, 7.117, 41.082, 0, "Sell"),
            ],
            [41.082],
            "in and out at one price: the averaged entry leaves 5.7e-14, which "
            "the tolerant add must snap to exactly zero",
        )
    )
    cases.append(
        Case(
            "zero_size_order_is_rejected",
            2,
            1,
            [order(0, 0, 0, 10, 0, "Buy")],
            [10.0],
            "a size of zero is an invariant violation, not an empty trade",
        )
    )
    cases.append(
        Case(
            "zero_price_order_is_rejected",
            2,
            1,
            [order(0, 0, 1, 0, 0, "Buy")],
            [10.0],
            "likewise a price of zero: the return would divide by it",
        )
    )
    return cases


def random_streams(seed: int, count: int) -> list[Case]:
    """Random order streams, dense in reversals and partial exits."""
    rng = random.Random(seed)
    cases = []
    for n in range(count):
        n_cols = rng.choice([1, 1, 2, 3])
        n_rows = rng.randint(4, 12)
        orders = []
        for col in range(n_cols):
            row = 0
            for _ in range(rng.randint(1, 6)):
                row += rng.randint(1, 2)
                if row >= n_rows:
                    break
                orders.append(
                    order(
                        row,
                        col,
                        round(rng.uniform(0.5, 3.0), 3),
                        round(rng.uniform(1.0, 20.0), 3),
                        round(rng.uniform(0.0, 0.5), 4),
                        rng.choice(["Buy", "Sell"]),
                    )
                )
        if not orders:
            continue
        cases.append(
            Case(
                f"random_{n:03d}",
                n_rows,
                n_cols,
                orders,
                [round(rng.uniform(1.0, 20.0), 3) for _ in range(n_cols)],
                "seeded random stream",
            )
        )
    return cases


def simulated(seed: int, count: int) -> list[Case]:
    """Streams produced by an actual simulation, for realistic input.

    The synthetic streams above reach states a simulation cannot, which is
    what makes them useful; these confirm the derivation also agrees on the
    fills the engine really produces.
    """
    rng = np.random.default_rng(seed)
    cases = []
    for n in range(count):
        n_rows, n_cols = 12, 2
        close = np.abs(rng.normal(20.0, 3.0, size=(n_rows, n_cols))) + 1.0
        size = rng.normal(0.0, 2.0, size=(n_rows, n_cols))
        size[rng.random(size.shape) < 0.4] = np.nan
        recs, _ = simulate_from_orders_nb(
            target_shape=(n_rows, n_cols),
            group_lens=np.full(n_cols, 1),
            init_cash=np.full(n_cols, 1000.0),
            call_seq=np.full((n_rows, n_cols), 0),
            size=size,
            price=close,
            size_type=np.asarray(SizeType.Amount),
            direction=np.asarray(Direction.Both),
            fees=np.asarray(0.01),
            fixed_fees=np.asarray(0.5),
            flex_2d=True,
        )
        if len(recs) == 0:
            continue
        orders = [
            (int(r["idx"]), int(r["col"]), float(r["size"]), float(r["price"]), float(r["fees"]), int(r["side"]))
            for r in recs
        ]
        cases.append(
            Case(
                f"simulated_{n:03d}",
                n_rows,
                n_cols,
                orders,
                [float(close[-1, c]) for c in range(n_cols)],
                "fills from an actual from_orders run",
            )
        )
    return cases


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "fixtures" / "trades.tsv",
    )
    parser.add_argument("--seed", type=int, default=20240917)
    args = parser.parse_args()

    cases = handpicked() + random_streams(args.seed, 60) + simulated(args.seed, 12)

    lines = ["\t".join(COLUMNS)]
    for case in cases:
        for view in VIEWS:
            fields = {k: "" for k in COLUMNS}
            fields.update(
                {
                    "case": case.name,
                    "view": view,
                    "n_rows": str(case.n_rows),
                    "n_cols": str(case.n_cols),
                    "close": ";".join(fmt_float(v) for v in case.close),
                    "orders": case.orders_text(),
                    "note": case.note,
                }
            )
            result = run(case, view)
            # Only the output fields are overwritten: an error case must stay
            # replayable, so its inputs and note survive.
            for key in ("outcome", *OUTPUT_FIELDS):
                if key in result:
                    fields[key] = result[key]
            if result.get("note"):
                fields["note"] = result["note"]
            lines.append("\t".join(fields[k] for k in COLUMNS))

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(lines) - 1} fixtures to {args.out}")


if __name__ == "__main__":
    main()
